def deep_html(m, names):
    """把讲透层渲染成五段 HTML；缺配置时返回空串，方便分批补齐。"""
    empty = dict(why='', parts='', bounds='', proof='', done='')
    d = DEEP.get(m['mid'])
    if not d:
        return empty
    why = ('<div class="mp-why"><span class="mp-deep-k">为什么管用</span><p>%s</p></div>'
           % fmt(d['why']))
    parts = ('<div class="mp-deep-head"><span class="mp-deep-k">拆成三块</span>'
             '<span class="mp-deep-hint">逐块检查，缺哪块就补哪块</span></div>'
             '<div class="mp-parts">%s</div>' % ''.join(
                 '<div class="mp-part"><b>%s</b><span>%s</span></div>' % (esc(a), fmt(b))
                 for a, b in d['parts']))
    vs_mid, vs_text = d['vs']
    vs_name = names[vs_mid]['name'] if vs_mid in names else vs_mid
    bounds = ('<div class="mp-deep-head"><span class="mp-deep-k">什么时候用，什么时候别用</span></div>'
              '<div class="mp-bounds">'
              '<div class="mp-bound ok"><b>该用</b><p>%s</p></div>'
              '<div class="mp-bound no"><b>别用 / 换招</b><p>%s</p></div>'
              '<div class="mp-bound vs"><b>别和「<a href="method-%s.html">%s</a>」搞混</b><p>%s</p></div>'
              '</div>' % (fmt(d['use']), fmt(d['skip']), esc(vs_mid), esc(vs_name), fmt(vs_text)))
    proof = ('<div class="mp-proof"><div class="mp-proof-head"><span class="mp-deep-k">一步一步推给你看</span>'
             '<span class="mp-deep-hint">用符号、句式或示意数字走一遍；涉及数字均为教学假设，不是调研数据</span></div>'
             '<ol class="mp-proof-list">%s</ol></div>' % ''.join(
                 '<li><b>%s</b><code>%s</code><span>%s</span></li>' % (esc(a), fmt(b), fmt(c))
                 for a, b, c in d['proof']))
    done = ('<div class="mp-done"><span class="mp-deep-k">做完该留下</span><ul>%s</ul></div>'
            % ''.join('<li>%s</li>' % fmt(x) for x in d['done']))
    return dict(why=why, parts=parts, bounds=bounds, proof=proof, done=done)


def tool_html(tool):
    kind = tool[0]
    if kind == 'check':
        rows = ''.join(
            '<label class="mp-check-row"><input type="checkbox"><span>%s</span><i>✓</i></label>' % esc(x)
            for x in tool[1])
        return ('<div class="mp-tool" data-mp-tool="check"><div class="mp-check-list">%s</div>'
                '<div class="mp-tool-out" aria-live="polite">勾一勾，看这一招你差哪一步。</div></div>' % rows)
    if kind == 'flip':
        cards = ''.join(
            '<button type="button" class="mp-flip" aria-pressed="false"><span class="mp-flip-face">%s</span>'
            '<span class="mp-flip-back">✓ 这条做到了吗？点一下确认</span></button>' % esc(x) for x in tool[1])
        return '<div class="mp-tool" data-mp-tool="flip"><div class="mp-flip-grid">%s</div></div>' % cards
    if kind == 'quiz':
        q, right, wrongs = tool[1]
        opts = [right] + list(wrongs)
        # 固定打散顺序，保证每次生成一致且正确答案不总在第一个
        order = [2, 0, 1] if len(opts) == 3 else [2, 0, 3, 1]
        opts = [opts[i] for i in order[:len(opts)]]
        btns = ''.join('<button type="button" class="mp-quiz-opt" data-ok="%d">%s</button>'
                       % (1 if x == right else 0, esc(x)) for x in opts)
        return ('<div class="mp-tool" data-mp-tool="quiz"><p class="mp-quiz-q">%s</p>'
                '<div class="mp-quiz-opts">%s</div><div class="mp-tool-out" aria-live="polite"></div></div>'
                % (esc(q), btns))
    if kind == 'slider':
        cfg = tool[1]
        vals = []
        v = cfg['mn']
        while v <= cfg['mx'] + 1e-9:
            vals.append('%s:%s' % (('%g' % v), cfg['calc'](v)))
            v += cfg['step']
        return ('<div class="mp-tool" data-mp-tool="slider" data-mn="%s" data-mx="%s" data-step="%s" '
                'data-vals="%s" data-formula="%s" data-label="%s">'
                '<input type="range" min="%s" max="%s" step="%s" value="%s" aria-label="%s">'
                '<div class="mp-slider-read"><span class="mp-slider-eq"></span><b class="mp-slider-res"></b></div>'
                '<div class="mp-tool-out" aria-live="polite"></div></div>'
                % (cfg['mn'], cfg['mx'], cfg['step'], ','.join(vals), esc(cfg['formula']), esc(cfg['label']),
                   cfg['mn'], cfg['mx'], cfg['step'], cfg['val'], esc(cfg['label'])))
    raise ValueError(kind)


