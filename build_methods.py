    assert not missing, 'missing DEEP entries: %s' % ','.join(missing)
    names = dict((m['mid'], m) for m in DATA)
    for i, m in enumerate(DATA):
        nxt = ('method-%s.html' % DATA[i + 1]['mid']) if i < 47 else 'methods.html'
        fn = os.path.join(ROOT, 'method-%s.html' % m['mid'])
        open(fn, 'w', encoding='utf-8', newline='').write(page_html(i, m, nxt, names))
    print('generated %d standalone pages' % len(DATA))
    rewrite_links()


