# ---------------------------------------------------------------- 文本与组件
def esc(s):
    return html.escape(str(s), quote=False)


def fmt(s):
    """[[..]] 高亮数字，**..** 加粗，其余转义。"""
    s = esc(s)
    s = re.sub(r'\[\[(.+?)\]\]', r'<em class="mp-hl">\1</em>', s)
    s = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', s)
    return s


def fig(num, kind, title, body, cap, note):
    return (
        '<figure class="fig mp-fig">'
        '<div class="fig-head"><span>FIG %02d · %s</span><span class="fig-title">%s</span></div>'
        '<div class="fig-body">%s</div>'
        '<figcaption><b>结论：</b>%s<span class="fig-note">口径：%s</span></figcaption>'
        '</figure>' % (num, esc(kind), esc(title), body, fmt(cap), esc(note))
    )


def norm(items, n):
    """把每项的字段数规范成 n：多余的忽略、不足补空，容忍配置里的手误。"""
    out = []
    for it in items:
        seq = list(it) if isinstance(it, (tuple, list)) else [it]
        out.append(tuple((seq + [''] * n)[:n]))
    return out


def render_chart(num, c):
    """把图表配置渲染成 figure。"""
    t = c['type']
    items = c['items']
    if t == 'flow':                       # [(序号, 标题, 说明)]
        body = '<div class="flow mp-flow">' + ''.join(
            '<div class="flow-step %s"><span class="no">%s</span><h4>%s</h4><span class="d">%s</span></div>'
            % (TONES[i % 4], esc(a), esc(b), esc(d))
            for i, (a, b, d) in enumerate(norm(items, 3))) + '</div>'
    elif t == 'bars':                     # [(标签, 百分比, 显示值)]
        body = '<div class="bars">' + ''.join(
            '<div class="bar-row"><span class="bar-label">%s</span><div class="bar-track">'
            '<div class="bar-fill %s" data-w="%s%%"></div></div><span class="bar-val">%s</span></div>'
            % (esc(a), 'teal' if i % 3 == 0 else ('blue' if i % 3 == 1 else 'lime'), b, esc(str(d)))
            for i, (a, b, d) in enumerate(norm(items, 3))) + '</div>'
    elif t == 'table':                    # (表头 list, 行 list[list])
        head, rows = items
        body = '<div class="table-scroll" style="margin-top:0"><table><thead><tr>' + ''.join(
            '<th>%s</th>' % esc(x) for x in head) + '</tr></thead><tbody>' + ''.join(
            '<tr>' + ''.join('<td>%s</td>' % fmt(x) for x in r) + '</tr>' for r in rows) + '</tbody></table></div>'
    elif t == 'matrix':                   # (横轴, 纵轴, [(格名, 说明)] x4)
        xl, yl, qs = items
        body = ('<div class="mp-matrix"><span class="mp-axis-y">%s</span><div class="mp-matrix-grid">%s</div>'
                '<span class="mp-axis-x">%s</span></div>' % (
                    esc(yl), ''.join('<div class="mp-quad q%d"><b>%s</b><span>%s</span></div>' % (i + 1, esc(a), esc(b))
                                     for i, (a, b) in enumerate(norm(qs, 2))), esc(xl)))
    elif t == 'cycle':                    # [(标题, 说明)]
        body = '<div class="mp-cycle">' + ''.join(
            '<div class="mp-cycle-node"><span class="mp-cycle-i">%02d</span><h4>%s</h4><span>%s</span></div>'
            % (i + 1, esc(a), esc(b)) for i, (a, b) in enumerate(norm(items, 2))) + '</div>'
    elif t == 'layers':                   # [(层名, 说明)]
        body = '<div class="mp-layers">' + ''.join(
            '<div class="mp-layer l%d"><b>%s</b><span>%s</span></div>' % (i + 1, esc(a), esc(b))
            for i, (a, b) in enumerate(norm(items, 2))) + '</div>'
    elif t == 'waterfall':                # [(标签, 相对高度, 显示值)]
        body = '<div class="mp-waterfall">' + ''.join(
            '<div class="mp-wf-col"><span class="mp-wf-val">%s</span><div class="mp-wf-bar" style="height:%s%%"></div><span class="mp-wf-lab">%s</span></div>'
            % (esc(str(d)), b, esc(a)) for a, b, d in norm(items, 3)) + '</div>'
    elif t == 'scale':                    # [(刻度名, 说明, 补充说明?)]
        body = '<div class="mp-scale">' + ''.join(
            '<div class="mp-scale-item"><span class="mp-scale-dot">%02d</span><div><b>%s</b><span>%s</span>%s</div></div>'
            % (i + 1, esc(a), esc(b), ('<small>%s</small>' % esc(d)) if d else '')
            for i, (a, b, d) in enumerate(norm(items, 3))) + '</div>'
    elif t == 'pyramid':                  # [(层名, 标题, 说明)]
        body = '<div class="mp-pyramid">' + ''.join(
            '<div class="mp-pyr-tier p%d"><span class="mp-pyr-lab">%s</span><div><b>%s</b><span>%s</span></div></div>'
            % (i + 1, esc(a), esc(b), esc(d)) for i, (a, b, d) in enumerate(norm(items, 3))) + '</div>'
    elif t == 'formula':                  # [(符号, 名称, 数值)]
        body = '<div class="mp-formula">' + ''.join(
            '<div class="mp-f-item"><span class="mp-f-sym">%s</span><b>%s</b><span>%s</span></div>' % (esc(a), esc(b), esc(d))
            for a, b, d in norm(items, 3)) + '</div>'
    elif t == 'compare':                  # (左标题, 左条目, 右标题, 右条目)
        lt, li, rt, ri = items
        def side(title, arr, cls):
            return '<div class="mp-cmp-col %s"><b>%s</b>%s</div>' % (
                cls, esc(title), ''.join('<span>%s</span>' % fmt(x) for x in arr))
        body = '<div class="mp-compare">' + side(lt, li, 'bad') + side(rt, ri, 'good') + '</div>'
    elif t == 'tree':                     # (根, [(枝名, 叶说明)])
        root, branches = items
        body = ('<div class="tree"><span class="tree-root">%s</span><div class="tree-branches">%s</div></div>'
                % (esc(root), ''.join('<span class="tree-leaf"><b>%s</b><span>%s</span></span>'
                                      % (esc(a), esc(b)) for a, b in norm(branches, 2))))
    else:
        raise ValueError('unknown chart type: ' + t)
    return fig(num, c.get('kind', '示意图'), c['title'], body, c['cap'], c['note'])


